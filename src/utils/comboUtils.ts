export const getCachedActiveCombos = (): Combo[] => {
  let list: Combo[] = [];
  try {
    const cached = localStorage.getItem('vrg_combos_cache');
    if (cached) {
      const parsed = JSON.parse(cached);
      if (Array.isArray(parsed) && parsed.length > 0) {
        list = parsed;
      }
    }
  } catch {}

  const diskList = (diskCombosData as any[]) || [];
  const map = new Map<string, any>();

  // 1. Seed with latest disk combos
  diskList.forEach(c => {
    if (c && c.id) map.set(c.id, { ...c });
  });

  // 2. Overlay cached combos while preserving disk overrides (order, freeDelivery, freePacking, onlyMetturService, imageUrl, products)
  list.forEach(c => {
    if (c && c.id) {
      const existing = map.get(c.id) || {};
      map.set(c.id, {
        ...existing,
        ...c,
        order: existing.order !== undefined ? existing.order : c.order,
        freeDelivery: existing.freeDelivery !== undefined ? existing.freeDelivery : c.freeDelivery,
        freePacking: existing.freePacking !== undefined ? existing.freePacking : c.freePacking,
        onlyMetturService: existing.onlyMetturService !== undefined ? existing.onlyMetturService : c.onlyMetturService,
        imageUrl: existing.imageUrl || c.imageUrl,
        products: (existing.products && existing.products.length > 0) ? existing.products : c.products
      });
    }
  });

  // Explicitly ensure Vinayagar Chaturthi combo is active, order 0, has 10 plants and correct festive image
  if (map.has('combo-vinayagar-chaturthi-10-fruit-plants')) {
    const vc = map.get('combo-vinayagar-chaturthi-10-fruit-plants');
    vc.order = 0;
    vc.active = true;
    vc.onlyMetturService = true;
    vc.freeDelivery = true;
    vc.freePacking = true;
    vc.imageUrl = '/products/vrg/combo-vinayagar-chaturthi-10-fruit-plants.jpg';
    if (!vc.products || vc.products.length < 10) {
      vc.products = VINAYAGAR_10_FRUIT_PLANTS;
    }
  }

  let deletedList: string[] = [];
  try {
    const rawDel = localStorage.getItem('vrg_deleted_combos');
    if (rawDel) {
      const pDel = JSON.parse(rawDel);
      if (Array.isArray(pDel)) deletedList = pDel;
    }
  } catch {}
  const deletedSet = new Set(deletedList);

  const prodMap = new Map<string, Product>();
  INITIAL_PRODUCTS.forEach(p => {
    if (p.id) {
      prodMap.set(p.id, p);
      prodMap.set(p.id.toLowerCase(), p);
    }
  });

  const dummyIds = new Set(['combo-1787635336437', 'combo-1787321846424', 'combo-1787577752349', 'combo-1787127554276']);

  return Array.from(map.values())
    .filter((c: any) => {
      if (!c || !c.id || c.active === false || deletedSet.has(c.id)) return false;
      if (dummyIds.has(c.id)) return false;
      if (!c.imageUrl && (!c.products || c.products.length === 0) && (!c.productIds || c.productIds.length === 0)) return false;
      return true;
    })
    .map((c: any) => {
      if (c.id === 'combo-vinayagar-chaturthi-10-fruit-plants') {
        return {
          ...c,
          products: (Array.isArray(c.products) && c.products.length >= 10) ? c.products : VINAYAGAR_10_FRUIT_PLANTS,
          onlyMetturService: true,
          freeDelivery: true,
          freePacking: true
        };
      }
      // If products array is empty, resolve from INITIAL_PRODUCTS by productIds
      if ((!c.products || c.products.length === 0) && Array.isArray(c.productIds) && c.productIds.length > 0) {
        const prods = c.productIds.map((pid: string) => prodMap.get(pid) || prodMap.get(pid.toLowerCase())).filter(Boolean);
        return { ...c, products: prods };
      }
      return c;
    })
    .sort((a: any, b: any) => (Number(a.order ?? 99) - Number(b.order ?? 99)));
};

/**
 * Accurately calculate the live plant count for any cart line item.
 * Expands combos into their full bundle size (e.g. 10 plants for the 10-Fruit Plants combo).
 */
export function getCartItemPlantCount(item: any): number {
  if (!item) return 0;
  const qty = typeof item.quantity === 'number' && item.quantity > 0 ? item.quantity : 1;
  const isCombo = item.isCombo ||
    item.product?.id?.startsWith('combo-') ||
    item.productId?.startsWith('combo-') ||
    item.comboId?.startsWith('combo-') ||
    (item.product as any)?.isCombo ||
    (item.product as any)?.categoryId === 'cat-combos' ||
    (item.product as any)?.categoryId === 'combos';

  if (!isCombo) return qty;

  // 1. Direct comboProducts array
  const cp = item.comboProducts || (item.product as any)?.comboProducts;
  if (Array.isArray(cp) && cp.length > 0) {
    return cp.length * qty;
  }

  // 2. Specific known combos by ID or Name
  const id = String(item.comboId || item.product?.id || item.productId || '').toLowerCase();
  const name = String(item.product?.name || item.comboTitle || '').toLowerCase();
  if (id.includes('10-fruit') || id.includes('vinayagar') || name.includes('விநாயகர்') || name.includes('சதுர்த்தி') || name.includes('10 fruit')) {
    return 10 * qty;
  }
  if (id.includes('water-apple-3') || id.includes('3-variety')) {
    return 3 * qty;
  }
  if (id.includes('fairy-rose') || id.includes('sunday-rose') || id.includes('2-variety')) {
    return 2 * qty;
  }
  if (id.includes('orchid-rose')) {
    return 1 * qty;
  }

  // 3. Regex on potSize (e.g. "10 Plants")
  const potSize = String(item.product?.potSize || '');
  const matchPot = potSize.match(/(\d+)\s*plant/i);
  if (matchPot) {
    return parseInt(matchPot[1], 10) * qty;
  }

  // 4. Regex on name / title / description
  const text = `${item.product?.name || ''} ${item.comboTitle || ''} ${item.product?.description || ''} ${item.product?.subtitle || ''}`;
  const matchText = text.match(/(\d+)\s*(?:fruit\s*|rose\s*|live\s*)?plants/i);
  if (matchText) {
    return parseInt(matchText[1], 10) * qty;
  }

  return 3 * qty; // Safe bundle fallback (never 1!)
}
